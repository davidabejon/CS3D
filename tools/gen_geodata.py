"""Generate source/gfx/geodata.c: the globe's land mask and country centres.

    python tools/gen_geodata.py

Downloads Natural Earth's 1:50m admin-0 countries (public domain), pinned to
a release and checked against its SHA-256, and writes:

  - a land mask: one bit per GRID_DEG x GRID_DEG cell, set when the cell's
    centre falls inside any country (Antarctica included);
  - a table of country label points (ISO 3166-1 alpha-2 -> lat, lon), used to
    place stations that come without coordinates.

The output is committed, so a normal build needs neither network nor this
script.
"""
import hashlib
import json
import urllib.request
from pathlib import Path

URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
       "v5.1.2/geojson/ne_50m_admin_0_countries.geojson")
SHA256 = "3e458fc036ad0a66411f2c1e6cac49c5d7bfb81cb1123bc513b22511a2b7fdeb"
GRID_DEG = 3
OUT = Path(__file__).resolve().parent.parent / "source" / "gfx" / "geodata.c"


def fetch() -> dict:
    print("Downloading Natural Earth countries...", flush=True)
    with urllib.request.urlopen(URL, timeout=90) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"SHA-256 mismatch: {digest}")
    return json.loads(data)


def rings_of(geometry: dict) -> list[list[list[float]]]:
    """Every ring (outer and holes) of a Polygon or MultiPolygon."""
    if geometry["type"] == "Polygon":
        return list(geometry["coordinates"])
    return [ring for poly in geometry["coordinates"] for ring in poly]


def inside(x: float, y: float, rings) -> bool:
    """Even-odd rule over all rings, so holes (lakes, enclaves) work."""
    hit = False
    for ring in rings:
        n = len(ring)
        j = n - 1
        for i in range(n):
            xi, yi = ring[i][0], ring[i][1]
            xj, yj = ring[j][0], ring[j][1]
            if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                hit = not hit
            j = i
    return hit


def main() -> None:
    features = fetch()["features"]
    shapes = []                      # (bbox, rings) per country
    centres: dict[str, tuple[int, float, float]] = {}
    for f in features:
        rings = rings_of(f["geometry"])
        xs = [p[0] for r in rings for p in r]
        ys = [p[1] for r in rings for p in r]
        shapes.append(((min(xs), min(ys), max(xs), max(ys)), rings))
        p = f["properties"]
        code = p["ISO_A2_EH"]
        if len(code) != 2 or not code.isalpha():
            continue
        # Several features can share a code (Australia's islands...): keep
        # the most prominent one.
        rank = p["LABELRANK"]
        if code not in centres or rank < centres[code][0]:
            centres[code] = (rank, p["LABEL_Y"], p["LABEL_X"])

    cols, rows = 360 // GRID_DEG, 180 // GRID_DEG
    bits = bytearray((cols * rows + 7) // 8)
    land = 0
    for row in range(rows):
        lat = 90 - (row + 0.5) * GRID_DEG
        for col in range(cols):
            lon = -180 + (col + 0.5) * GRID_DEG
            for (x0, y0, x1, y1), rings in shapes:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and inside(lon, lat, rings):
                    k = row * cols + col
                    bits[k >> 3] |= 1 << (k & 7)
                    land += 1
                    break
    print(f"{land} land cells of {cols * rows}; {len(centres)} countries")

    lines = [
        "/* Generated by tools/gen_geodata.py from Natural Earth 1:50m admin-0",
        " * countries (public domain). Do not edit. */",
        '#include "geodata.h"',
        "",
        f"const unsigned char GEO_LAND[{len(bits)}] = {{",
    ]
    for i in range(0, len(bits), 16):
        lines.append("\t" + ", ".join(f"0x{b:02X}" for b in bits[i:i + 16]) + ",")
    lines += ["};", "", "const geo_country GEO_COUNTRIES[] = {"]
    for code in sorted(centres):
        _, lat, lon = centres[code]
        lines.append(f'\t{{"{code}", {lat:.2f}f, {lon:.2f}f}},')
    lines += ["};", "",
              "const int GEO_COUNTRY_COUNT =",
              "\t(int)(sizeof(GEO_COUNTRIES) / sizeof(GEO_COUNTRIES[0]));", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
